#!/usr/bin/env python3
"""Compile the root certificate bundle into Tachyon.

Usage: gen_cacerts.py cacert.pem OUTPUT.c

Converts each PEM certificate to DER (smaller, and Mbed TLS parses it without
a copy) and writes a table for src/core/tc_cacerts.h, with the bundle's
labels so error messages and diagnostics can name a root.
"""

import base64
import sys


def read_bundle(path):
    certs, label, lines, inside = [], None, [], False
    with open(path, encoding="ascii") as f:
        for line in f:
            line = line.strip()
            if line.startswith("# Label:"):
                label = line.split(":", 1)[1].strip().strip('"')
            elif line == "-----BEGIN CERTIFICATE-----":
                inside, lines = True, []
            elif line == "-----END CERTIFICATE-----":
                certs.append((label or "unnamed", base64.b64decode("".join(lines))))
                inside, label = False, None
            elif inside:
                lines.append(line)
    return certs


def c_label(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("?", "\\?") + '"'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    certs = read_bundle(sys.argv[1])
    if not certs:
        sys.exit("gen_cacerts.py: no certificates in " + sys.argv[1])
    with open(sys.argv[2], "w", encoding="ascii") as out:
        out.write("/* Generated by tools/gen_cacerts.py from third_party/cacert/cacert.pem. Do not edit. */\n")
        out.write('#include "tc_cacerts.h"\n\n')
        for i, (_, der) in enumerate(certs):
            out.write("static const unsigned char cert_%d[%d] = {\n" % (i, len(der)))
            for j in range(0, len(der), 16):
                out.write("    " + ", ".join("0x%02x" % b for b in der[j:j + 16]) + ",\n")
            out.write("};\n")
        out.write("\nconst tc_cacert tc_cacerts[] = {\n")
        for i, (label, der) in enumerate(certs):
            out.write("    { %s, cert_%d, %d },\n" % (c_label(label), i, len(der)))
        out.write("};\n\nconst size_t tc_cacerts_count = %d;\n" % len(certs))


if __name__ == "__main__":
    main()
