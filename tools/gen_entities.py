#!/usr/bin/env python3
"""Compile the HTML named character references into a sorted C table.

Usage: gen_entities.py entities.js OUTPUT.c

entities.js is web-platform-tests' copy of the HTML Standard's table: lines
like  '&amp;': { 'codepoints': [0x00026], 'characters': '\\x26' },
"""

import re
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    text = open(sys.argv[1], encoding="utf-8").read()
    entities = {}
    for m in re.finditer(r"'&([A-Za-z0-9]+;?)': \{ 'codepoints': \[([^\]]*)\]", text):
        cps = [int(x, 16) for x in m.group(2).split(",")]
        if not 1 <= len(cps) <= 2 or (len(cps) == 2 and cps[1] > 0xFFFF):
            sys.exit("gen_entities.py: unexpected code points for &%s" % m.group(1))
        entities[m.group(1)] = cps
    if len(entities) != 2231:
        sys.exit("gen_entities.py: expected 2231 names, found %d" % len(entities))
    names = sorted(entities, key=lambda n: n.encode("ascii"))
    with open(sys.argv[2], "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/gen_entities.py from the HTML Standard. Do not edit. */\n")
        out.write('#include "tc_entities.h"\n\n')
        out.write("const tc_entity tc_entities[] = {\n")
        for name in names:
            cps = entities[name] + [0]
            out.write('    { "%s", 0x%X, 0x%X },\n' % (name, cps[0], cps[1]))
        out.write("};\n\nconst size_t tc_entity_count = %d;\n" % len(names))
        out.write("const size_t tc_entity_max_len = %d;\n" % max(len(n) for n in names))


if __name__ == "__main__":
    main()
