#!/usr/bin/env python3
"""Compile the user-agent style sheets into C strings.

Usage: gen_ua_css.py ua.css ua-quirks.css OUTPUT.c

Comments and indentation are dropped to keep the executable small; the
sheets are otherwise compiled in as written.
"""

import re
import sys


def squeeze(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    lines = [line.strip() for line in css.splitlines()]
    return "\n".join(line for line in lines if line) + "\n"


def c_string(text):
    out = []
    for line in text.splitlines(True):
        line = line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        out.append('    "%s"' % line)
    return "\n".join(out)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    sheets = [squeeze(open(path, encoding="utf-8").read()) for path in sys.argv[1:3]]
    for sheet in sheets:
        if any(ord(c) > 127 for c in sheet):
            sys.exit("gen_ua_css.py: keep the style sheets ASCII (use CSS escapes)")
    with open(sys.argv[3], "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/gen_ua_css.py from src/core/ua.css and ua-quirks.css. Do not edit. */\n")
        out.write('#include "tc_style_internal.h"\n\n')
        out.write("const char tc_ua_css[] =\n%s;\n\n" % c_string(sheets[0]))
        out.write("const char tc_ua_quirks_css[] =\n%s;\n" % c_string(sheets[1]))


if __name__ == "__main__":
    main()
