#!/usr/bin/env python3
"""Sample the WHATWG Encoding Standard's Chinese, Japanese and Korean
indexes for the unit tests: every 7th entry of each, plus its first and
last, as (pointer, code point) pairs. The tests turn each pointer into the
bytes that encode it and check that it decodes to the code point.

Usage: gen_encoding_tests.py INDEX_DIR OUTPUT.c
"""

import os
import sys

INDEXES = ["jis0208", "jis0212", "gb18030", "big5", "euc-kr"]


def read(path):
    pairs = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                pointer, code_point = line.split("\t")[:2]
                pairs.append((int(pointer), int(code_point, 16)))
    return pairs


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    out = ["/* Generated by tools/gen_encoding_tests.py. Do not edit. */\n",
           "#include <stddef.h>\n#include <stdint.h>\n\n"]
    for name in INDEXES:
        pairs = read(os.path.join(sys.argv[1], "index-%s.txt" % name))
        sample = pairs[::7] + [pairs[-1]]
        ident = "tc_test_index_" + name.replace("-", "_")
        out.append("const uint32_t %s[] = {\n" % ident)
        for i in range(0, len(sample), 6):
            out.append("    " + " ".join("%d, 0x%X," % p for p in sample[i:i + 6]) + "\n")
        out.append("};\nconst size_t %s_len = %d;\n\n" % (ident, len(sample)))
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main()
