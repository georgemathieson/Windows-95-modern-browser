#!/usr/bin/env python3
"""Turn web-platform-tests' URL data into C tables for test_url.c.

Usage: gen_url_tests.py urltestdata.json toascii.json known_failures.txt OUTPUT.c

known_failures.txt lists cases Tachyon is known to get wrong, one per line:
a JSON array followed by "# reason": [input, base] for urltestdata.json,
["toascii", input] for toascii.json. The test fails if one of them
unexpectedly passes, so the list can't go stale.
"""

import json
import sys


def usv(s):
    """JavaScript USVString conversion: lone surrogates become U+FFFD."""
    return s.encode("utf-16", "surrogatepass").decode("utf-16", "replace")


def c_string(s):
    """A C string literal for UTF-8 text, safe for any byte (including NUL,
    and '?' which -std=c99 would read as part of a trigraph)."""
    if s is None:
        return "NULL"
    out = []
    for b in usv(s).encode("utf-8"):
        ch = chr(b)
        if ch in '"\\?':
            out.append("\\" + ch)
        elif 0x20 <= b < 0x7F:
            out.append(ch)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def c_len(s):
    return len(usv(s).encode("utf-8"))


def load_known_failures(path):
    known = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            body, _, reason = line.partition("#")
            body = body.strip()
            if body:
                key = tuple(json.loads(body))
                known[key] = reason.strip() or "known failure"
    return known


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    tests = [t for t in json.load(open(sys.argv[1], encoding="utf-8")) if isinstance(t, dict)]
    hosts = [t for t in json.load(open(sys.argv[2], encoding="utf-8")) if isinstance(t, dict)]
    known = load_known_failures(sys.argv[3])
    rows = []
    for t in tests:
        key = (t["input"], t.get("base"))
        failure = 1 if t.get("failure") else 0
        fields = ["href", "protocol", "username", "password", "host", "hostname", "port",
                  "pathname", "search", "hash"]
        values = [c_string(None if failure else t.get(name)) for name in fields]
        rows.append("    { %s, %d, %s, %d, %s, %s },\n" % (
            c_string(t["input"]), c_len(t["input"]), c_string(t.get("base")), failure,
            ", ".join(values), c_string(known.get(key))))
        known.pop(key, None)
    host_rows = []
    for t in hosts:
        key = ("toascii", t["input"])
        host_rows.append("    { %s, %d, %s, %s },\n" % (
            c_string(t["input"]), c_len(t["input"]), c_string(t["output"]), c_string(known.get(key))))
        known.pop(key, None)
    if known:
        sys.exit("gen_url_tests.py: known failures not in the test data: %r" % list(known))
    with open(sys.argv[4], "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/gen_url_tests.py from web-platform-tests. Do not edit. */\n")
        out.write('#include "url_cases.h"\n\nconst url_case url_cases[] = {\n')
        out.writelines(rows)
        out.write("};\n\nconst size_t url_case_count = %d;\n" % len(rows))
        out.write("\nconst host_case host_cases[] = {\n")
        out.writelines(host_rows)
        out.write("};\n\nconst size_t host_case_count = %d;\n" % len(host_rows))


if __name__ == "__main__":
    main()
