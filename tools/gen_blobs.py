#!/usr/bin/env python3
"""Compile test files into C arrays, so the unit tests carry them (natively
and under Wine alike) without reading files.

Usage: gen_blobs.py OUT.c FILE...

OUT.c defines tc_test_blobs[] ({name, data, len}, by file name) and
tc_test_blob_count; tests/tc_test.h declares them.
"""

import os
import sys


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    out, files = sys.argv[1], sorted(sys.argv[2:], key=os.path.basename)
    lines = ["/* Generated by tools/gen_blobs.py. */", '#include "tc_test.h"', ""]
    for i, path in enumerate(files):
        data = open(path, "rb").read()
        lines.append("static const unsigned char blob_%d[%d] = {" % (i, max(len(data), 1)))
        for j in range(0, len(data), 16):
            lines.append("    " + ", ".join("%d" % b for b in data[j:j + 16]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("const tc_test_blob tc_test_blobs[] = {")
    for i, path in enumerate(files):
        lines.append('    { "%s", blob_%d, %d },' % (os.path.basename(path), i, os.path.getsize(path)))
    lines.append("    { 0, 0, 0 }")
    lines.append("};")
    lines.append("const size_t tc_test_blob_count = %d;" % len(files))
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
