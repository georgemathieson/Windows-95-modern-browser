#!/usr/bin/env python3
"""Turn css-parsing-tests into a C table for test_css.c.

Usage: gen_css_tests.py TEST_DIR KNOWN_FAILURES OUTPUT.c

- TEST_DIR: css-parsing-tests' *.json files.
- KNOWN_FAILURES: test ids ("file.json:N", N counting cases from 0) Tachyon
  gets wrong on purpose, one per line with the reason after '#'. A listed
  case that passes fails the run, so the list can't go stale.

Each case's expected result is written in a canonical JSON form that
test_css.c also produces from Tachyon's output: no spaces, strings with
only '"', '\\' and control characters escaped (non-ASCII stays UTF-8), and
numbers as "%.17g" (zero always "0").
"""

import json
import os
import sys

FILES = [
    "component_value_list", "one_component_value", "declaration_list", "blocks_contents",
    "one_declaration", "one_rule", "rule_list", "stylesheet", "stylesheet_bytes", "An+B",
    "color_keywords_3", "color_keywords_4", "color_hexadecimal_3", "color_hexadecimal_4",
    "color_hsl_3", "color_hsl_4", "color_hwb_4", "color_function_4", "color_functions_5",
    "color_lab_4", "color_lch_4", "color_oklab_4", "color_oklch_4",
]


def canon(x):
    if x is None:
        return "null"
    if x is True:
        return "true"
    if x is False:
        return "false"
    if isinstance(x, (int, float)):
        return "0" if x == 0 else "%.17g" % float(x)
    if isinstance(x, str):
        out = ['"']
        for ch in x:
            if ch == '"':
                out.append('\\"')
            elif ch == "\\":
                out.append("\\\\")
            elif ord(ch) < 0x20 or ord(ch) == 0x7F:
                out.append("\\u%04x" % ord(ch))
            else:
                out.append(ch)
        out.append('"')
        return "".join(out)
    if isinstance(x, list):
        return "[" + ",".join(canon(i) for i in x) + "]"
    sys.exit("gen_css_tests.py: unexpected JSON value %r" % (x,))


def c_bytes(b):
    """A C string literal for any bytes ('?' escaped against trigraphs)."""
    if b is None:
        return "NULL"
    out = []
    for x in b:
        ch = chr(x)
        if ch in '"\\?':
            out.append("\\" + ch)
        elif 0x20 <= x < 0x7F:
            out.append(ch)
        else:
            out.append("\\%03o" % x)
    return '"' + "".join(out) + '"'


def utf8(s):
    return s.encode("utf-8", "surrogatepass")


def load_known(path):
    known = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            body, _, reason = line.partition("#")
            body = body.strip()
            if body:
                known[body] = reason.strip() or "known failure"
    return known


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    known = load_known(sys.argv[2])
    used = set()
    rows = []
    for name in FILES:
        with open(os.path.join(sys.argv[1], name + ".json"), encoding="utf-8") as f:
            data = json.load(f)
        for n in range(0, len(data), 2):
            ident = "%s.json:%d" % (name, n // 2)
            given, expected = data[n], data[n + 1]
            protocol = environment = None
            if isinstance(given, dict):
                raw = bytes(ord(c) for c in given["css_bytes"])
                protocol = given.get("protocol_encoding")
                environment = given.get("environment_encoding")
            else:
                raw = utf8(given)
            reason = known.get(ident)
            if reason:
                used.add(ident)
            rows.append("    { %s, %s, %s, %d, %s, %s, %s, %s },\n" % (
                c_bytes(name.encode()), c_bytes(ident.encode()), c_bytes(raw), len(raw),
                c_bytes(utf8(protocol)) if protocol is not None else "NULL",
                c_bytes(utf8(environment)) if environment is not None else "NULL",
                c_bytes(utf8(canon(expected))), c_bytes(reason.encode()) if reason else "NULL"))
    stale = sorted(set(known) - used)
    if stale:
        sys.exit("gen_css_tests.py: known failures that aren't tests: %r" % stale)
    with open(sys.argv[3], "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/gen_css_tests.py from css-parsing-tests. Do not edit. */\n")
        out.write("#include \"css_cases.h\"\n\nconst css_case css_cases[] = {\n")
        out.writelines(rows)
        out.write("};\nconst size_t css_case_count = sizeof css_cases / sizeof css_cases[0];\n")


if __name__ == "__main__":
    main()
